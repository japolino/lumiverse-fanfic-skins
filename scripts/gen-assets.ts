// Inlines everything in assets/ as data URIs so the frontend bundle is a
// single file with no extra requests to the extension's static path.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, extname, basename } from "node:path";

const root = join(import.meta.dir, "..");
const assetsDir = join(root, "assets");
const outDir = join(root, "src", "generated");
mkdirSync(outDir, { recursive: true });

const mime: Record<string, string> = {
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".webp": "image/webp",
};

const lines = ["// Generated by scripts/gen-assets.ts. Do not edit.", ""];
for (const file of readdirSync(assetsDir).sort()) {
  const type = mime[extname(file)];
  if (!type) continue;
  const name = basename(file, extname(file)).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
  const data = readFileSync(join(assetsDir, file)).toString("base64");
  lines.push(`export const ${name} = "data:${type};base64,${data}";`);
}
writeFileSync(join(outDir, "assets.ts"), lines.join("\n") + "\n");
console.log(`assets: wrote ${lines.length - 2} data URIs`);
